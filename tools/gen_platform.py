def _显示宽度(文本: str) -> int:
    """显示宽度 —— **复用语言自身的唯一实现**（`shuyan.source.display_width`）。

    为什么不在这里另写一份：宽度算法（汉字算 2 列）若有两处实现必然分叉，
    而生成器超宽与否的判断与语言 W4202 的判断必须**同口径**，否则会出现
    「生成器认为不超宽、语言却报 W4202」的鬼故事。
    """
    from shuyan.source import display_width
    return display_width(文本)


def 折引入行(关键字: str, 成员: list[str], 模块: str,
            最大宽: int = 100) -> list[str]:
    """把一条超宽的按名引入折成多条同行宽度的引入语句。

    枢言的引入语句**允许同一模块重复引入**（已在源码实测确认：三条
    `引入 { X } 从 "M"` 与一条合并写法等价），故折行的语义是安全的 ——
    这正是不必发明新续行语法的原因。

    折行只在**成员之间**发生（一个成员绝不会被切断），且尽量填满一行，
    使产物既不过宽、也不碎片化。
    """
    前缀 = f"引入 {{ "
    后缀 = f' }} 从 "{模块}"'
    # 先按「一个成员也放不下」的极端情形兜底：此时无法折行，原样返回
    最小行 = 前缀 + 成员[0] + 后缀 if 成员 else 前缀 + 后缀
    if _显示宽度(最小行) > 最大宽:
        return [前缀 + ", ".join(成员) + 后缀]

    行们: list[str] = []
    当前: list[str] = []
    for 名 in 成员:
        试 = 前缀 + ", ".join(当前 + [名]) + 后缀
        if 当前 and _显示宽度(试) > 最大宽:
            行们.append(前缀 + ", ".join(当前) + 后缀)
            当前 = [名]
        else:
            当前.append(名)
    if 当前:
        行们.append(前缀 + ", ".join(当前) + 后缀)
    return 行们


def 折叠超宽引入(文本: str, 最大宽: int = 100) -> str:
    """扫描全文，把**超宽的按名引入行**替换为折行后的多条。

    只动超宽的那些行；不超宽的一律原样保留（生成的产物要让人看得懂，
    不能为了整齐把每一条都拆碎）。
    """
    import re
    行 = 文本.split("\n")
    结果: list[str] = []
    for 原行 in 行:
        m = re.match(r'^引入\s*\{([^}]*)\}\s*从\s*"([^"]+)"\s*$', 原行.strip())
        if m and _显示宽度(原行) > 最大宽:
            成员 = [x.strip() for x in m.group(1).split(",") if x.strip()]
            结果.extend(折引入行("引入", 成员, m.group(2), 最大宽))
        else:
            结果.append(原行)
    return "\n".join(结果)


def 补全引入(文本: str, 本模块名: str, 可用: dict[str, list[str]]) -> str:
    """按**实际调用**补全引入 —— 不靠手工维护依赖表。

    做法：扫出源码里形如 `名字(` 的调用，减去本文件自己定义的函数，
    再看哪些属于某个依赖模块的导出清单；缺哪个就补那个模块的按名引入。

    为什么用自动补全而不是手写依赖表：手写表一旦漏项，症状是
    `D3005 没有定义函数「X」` —— 报错点在调用处，真因却在文件头的
    引入行，排查要绕一圈。自动补全让「写了调用就一定有引入」成为
    生成器的不变量，这类错误从根上不会出现。
    """
    import re
    # 本文件定义的名字（`请 名字(`），以及类型名
    自己定义 = set(re.findall(r"^请\s+([^\s(（]+)", 文本, re.M))
    自己定义 |= set(re.findall(r"^类型\s+([^\s=]+)", 文本, re.M))
    # 本文件已有的按名引入
    已有: dict[str, str] = {}
    for m in re.finditer(r'^引入\s*\{([^}]*)\}\s*从\s*"([^"]+)"', 文本, re.M):
        名字们 = [x.strip() for x in m.group(1).split(",") if x.strip()]
        for n in 名字们:
            已有[n] = m.group(2)

    调用名 = set(re.findall(r"([^\s(（,，\[\]\.]{1,20})\(", 文本))
    需要: dict[str, list[str]] = {}
    for 名 in 调用名:
        if 名 in 自己定义:
            continue
        for 模块, 名单 in 可用.items():
            if 模块 == 本模块名:
                continue
            if 名 in 名单:
                已有该 = 已有.get(名)
                if 已有该 == 模块:
                    break            # 已引入，无需补
                if 名 not in 自己定义:
                    需要.setdefault(模块, []).append(名)
                break

    if not 需要:
        return 文本
    # 生成补充引入行，插在最后一条引入语句之后
    补充 = []
    for 模块 in sorted(需要):
        补充.append(f'引入 {{ {", ".join(sorted(set(需要[模块]))) } }} '
                  f'从 "{模块}"')
    行 = 文本.split("\n")
    插入位 = 0
    for i, l in enumerate(行):
        if l.startswith("引入 "):
            插入位 = i + 1
    if 插入位 == 0:
        return 文本
    return "\n".join(行[:插入位] + 补充 + 行[插入位:])


def build(outdir: str, n_domains: int, n_entities: int, n_rules: int,
          seed: int) -> dict:
    rng = random.Random(seed)
    域清单 = 域定义[:n_domains]
    # 每个域截取到 n_entities 个实体
    for 域 in 域清单:
        域["实体"] = 域["实体"][:n_entities]

    files: dict[str, str] = {}

    # 框架层
    files["框架/基础.sy"] = gen_框架_基础()
    files["框架/事件.sy"] = gen_框架_事件()
    files["框架/工作流.sy"] = gen_框架_工作流()
    files["框架/权限.sy"] = gen_框架_权限()
    files["框架/规则.sy"] = gen_框架_规则()
    files["框架/审计.sy"] = gen_框架_审计()
    files["框架/报表.sy"] = gen_框架_报表()

    # 域层
    for 域 in 域清单:
        d = 域["slug"]
        files[f"{d}/模型.sy"] = gen_域_模型(域)
        files[f"{d}/仓储.sy"] = gen_域_仓储(域)
        files[f"{d}/服务.sy"] = gen_域_服务(域)
        files[f"{d}/规则.sy"] = gen_域_规则(域, n_rules)
        files[f"{d}/报表.sy"] = gen_域_报表(域)

    # 主程序
    files["主程序.sy"] = gen_主程序(域清单)

    total_lines = 0
    # 先给每个文件做续行规范化，再**从源码自动提取每个模块导出的成员** ——
    # 这样即便模板改了函数名，补全清单也不会过期（手写清单漏一项就是
    # 「D3005 没有定义函数」，报错点在调用处、真因在引入行）。
    规范后: dict[str, str] = {f: 规范续行(t) for f, t in files.items()}
    import re as _re

    def _导出成员(文本: str) -> list[str]:
        名 = _re.findall(r"^请\s+([^\s(（]+)", 文本, _re.M)
        名 += _re.findall(r"^类型\s+([^\s=]+)", 文本, _re.M)
        见过: list[str] = []
        for n in 名:
            if n not in 见过:
                见过.append(n)
        return 见过

    可用: dict[str, list[str]] = {
        f[:-3].replace("\\", "/"): _导出成员(t)
        for f, t in 规范后.items() if f.endswith(".sy")
    }

    for fname, text in 规范后.items():
        path = os.path.join(outdir, fname)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        本模块 = fname[:-3].replace("\\", "/") if fname.endswith(".sy") \
            else fname
        text = 补全引入(text, 本模块, 可用)
        # 补全引入可能把成员堆成超宽行（一个域 12 个实体时必然超宽）。
        # 这里统一折行 —— 保证**生成的产物零警告**，否则 `make 平台`
        # 的「检查」一步会满屏 W4202。
        text = 折叠超宽引入(text)
        # 统一以换行结尾（文本文件惯例）。这样「工具报的行数」=
        # 「`wc -l` 的行数」=「逻辑行数」，三处口径一致，不会再出现
        # 对外声明的数字与实测对不上的情况。
        if not text.endswith("\n"):
            text += "\n"
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        total_lines += text.count("\n")

    return {"files": len(files), "lines": total_lines,
            "domains": len(域清单), "entities": len(域清单) * n_entities}


