# ============================================================ 主流程

def 规范续行(文本: str) -> str:
    """把**行首运算符**挪到上一行行尾（而非整行合并）。

    为什么需要：枢言的续行规则是「运算符须写在**上一行行尾**」，
    行首的 `+` 会被当成新语句（一元正号），整条拼接断裂后
    「算完就丢」，报 D2012。而用三引号写生成器时，为了让 Python
    源码行不太长，很自然就会把 `+` 留在下一行行首 —— 生成的源码
    于是非法。与其逐处手改（易漏），不如在此统一规范化。

    做法：若某行（去掉缩进后）以二元运算符开头，就**只把该运算符**
    移到上一行末尾，本行剩余的表达式照旧留在原位（保持原缩进）。
    注意不能把整行接到上一行 —— 那样拼出来是一行超长语句，
    会触发 W4202（本工程要求零警告）。移运算符与整行合并**语义相同**，
    但前者不会把行拉长。
    """
    运算符 = ("+", "-", "*", "/", "%", "==", "!=", ">=", "<=", ">", "<",
            "且", "或")
    行 = 文本.split("\n")
    结果: list[str] = []
    for 原行 in 行:
        去缩进 = 原行.strip()
        前缀 = 原行[:len(原行) - len(原行.lstrip())]
        命中 = None
        if 去缩进 and 去缩进[0] != "#":
            for op in 运算符:
                if 去缩进.startswith(op + " "):
                    命中 = op
                    break
        if 结果 and 命中 is not None:
            剩余 = 去缩进[len(命中):].strip()
            结果[-1] = 结果[-1].rstrip() + " " + 命中
            if 剩余:
                结果.append(前缀 + 剩余)
        else:
            结果.append(原行)
    return "\n".join(结果)


