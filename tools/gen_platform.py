# ============================================================ 域生成

def gen_域_模型(域: dict) -> str:
    """域模型：实体类型 + 枚举 + 构造辅助。"""
    行 = [f'''// ============================================================ {域["名称"]} · 模型
//
// {域["用途"]}
//
// 本文件只放**类型定义与构造辅助**，不含任何业务逻辑。
// 类型的字段顺序只在这里维护一次：字段增删只改本文件，
// 业务代码不受影响（它们一律走构造辅助）。

// 模型层只用内置函数，不依赖框架/基础 —— 保持最底层零依赖。

// ------------------------------------------------------------ 本域状态枚举

类型 本域状态 = {{ 草稿, 已提交, 已审批, 已执行, 已完成, 已作废 }}

''']
    for 实体, 形态 in 域["实体"]:
        行.append(f'''// ------------------------------------------------------------ {实体}

类型 {实体} = {{
    编号: 文本,
    名称: 文本,
    状态: 本域状态,
    主责人: 文本,
    建立日期: 文本,''')
        for 字段名, 字段型 in 形态字段[形态]:
            行.append(f"    {字段名}: {字段型},")
        行.append("}")
        行.append("")

    行.append(f'''请 {_前缀(域)}_造状态(名)
    如果 名 是 "草稿" 则
        返回 本域状态.草稿
    结束
    如果 名 是 "已提交" 则
        返回 本域状态.已提交
    结束
    如果 名 是 "已审批" 则
        返回 本域状态.已审批
    结束
    如果 名 是 "已执行" 则
        返回 本域状态.已执行
    结束
    如果 名 是 "已完成" 则
        返回 本域状态.已完成
    结束
    返回 本域状态.已作废
结束

''')
    # 构造辅助：字段顺序收拢到一处
    for 实体, 形态 in 域["实体"]:
        形参 = "编号, 名称, 状态, 主责人, 建立日期"
        for 字段名, _ in 形态字段[形态]:
            形参 = 形参 + ", " + 字段名
        行.append(f"请 {_前缀(域)}_造{实体}({形参})")
        行.append(f"    返回 {实体}(编号 是 编号, 名称 是 名称, 状态 是 状态,")
        行.append(f"    主责人 是 主责人, 建立日期 是 建立日期,")
        部件 = []
        for 字段名, _ in 形态字段[形态]:
            部件.append(f"{字段名} 是 {字段名}")
        # 每行最多 3 个字段，避免超长
        for i in range(0, len(部件), 3):
            片段 = 部件[i:i + 3]
            结尾 = ")" if i + 3 >= len(部件) else ","
            行.append("    " + ", ".join(片段) + 结尾)
        行.append("结束")
        行.append("")
    return "\n".join(行)


