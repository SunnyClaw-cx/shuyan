def gen_域_规则(域: dict, n_rules: int) -> str:
    """域规则：可枚举的校验规则表 + 判定。"""
    行 = [f'''// ============================================================ {域["名称"]} · 规则
//
// 规则层：把本域所有的「拦得住 / 提醒」判定收成**可枚举的规则表**。
//
// 为什么要有这层：业务规则会随监管与内控要求不断加。若它们散落在服务
// 函数里，没人答得出「一共多少条规则、哪条最严」。这里每条规则都是
// 一个具名结构体，可列举、可统计、可按严重度排序。

引入 "框架/规则"
引入 "{域["slug"]}/模型"
引入 {{ {", ".join(实体 for 实体, _ in 域["实体"])} }} 从 "{域["slug"]}/模型"

''']
    P = _前缀(域)
    for 实体, 形态 in 域["实体"]:
        严重度们 = ["拦截", "警告", "提示"]
        行.append(f"// ------------------------------------------------------------ {实体} 规则\n")
        行.append(f"请 {P}_{实体}规则表()")
        行.append("    定义 结果 = [")
        定义部分 = []
        for i in range(1, n_rules + 1):
            严重度 = 严重度们[i % 3]
            定义部分.append(
                f'    造规则("{P}-{实体}-{i:03d}", "{实体}规则{i}", '
                f'"{严重度}", "条件{i}", "结论{i}")')
        行.append(",\n".join(定义部分))
        行.append("    ]")
        行.append("    返回 结果")
        行.append("结束")
        行.append("")
        # 判定：对某记录跑全部规则（条件由本函数就地给出，仍有类型检查）
        行.append(f"请 {P}_{实体}判定(某记录)")
        行.append(f"    定义 规则们 = {P}_{实体}规则表()")
        行.append("    定义 判定表 = [")
        判定部分 = []
        for i in range(1, n_rules + 1):
            # 让条件有真实语义：与形态相关的判据
            if 形态 == "金额":
                cond = f"某记录.金额 > {i} * 1000"
            elif 形态 == "数量":
                cond = f"某记录.数量 > {i} * 10"
            elif 形态 == "状态":
                cond = f"某记录.轮数 > {i}"
            elif 形态 == "时间":
                cond = f"某记录.账期天数 > {i} * 15"
            elif 形态 == "层级":
                cond = f"某记录.层级 > {i}"
            else:
                cond = f"某记录.启用 且 {i} % 2 是 1"
            判定部分.append(f"    [规则们[{i - 1}], {cond}]")
        行.append(",\n".join(判定部分))
        行.append("    ]")
        行.append("    返回 命中项清单(判定表)")
        行.append("结束")
        行.append("")
        行.append(f"请 {P}_{实体}可否放行(某记录)")
        行.append(f"    返回 非 有拦截({P}_{实体}判定(某记录))")
        行.append("结束")
        行.append("")
    return "\n".join(行)


