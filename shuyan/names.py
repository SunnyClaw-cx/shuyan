# 它们是关键字，必须保持关键字身份，否则 `输出(空)` 会变成未定义标识符。
# 类型标注位置由解析器直接接受关键字，不需要本表保护。
TYPE_NAMES: frozenset[str] = frozenset({
    "整数", "小数", "文本", "布尔", "列表", "映射", "任意",
})

# 与关键字同形、因而**不得**进入保留名表的类型名（仅供一致性检查使用）
KEYWORD_COLLIDING_TYPE_NAMES: frozenset[str] = frozenset({"空", "函数"})

# 词法层需整体保护的完整集合
PROTECTED_NAMES: frozenset[str] = BUILTIN_NAMES | TYPE_NAMES