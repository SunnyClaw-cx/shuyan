"""枢言语言 —— 语言保留名清单（内置函数与模块名）。

**为什么单独成模块**：词法层在切分汉字块时，必须知道「哪些名字是语言
自带的」。否则 `类型名` 会被 `类型`（A 类引导词）前缀匹配切成
`类型` + `名`，标准库函数直接失效。

`类型名` 这类「以关键字开头」的内置名是中文语言的固有风险 —— 关键字是
短词、内置名是词组，前缀必然冲突。解决方式是在切分前加一道**整体命中保护**：
整个字块若命中保留名，则不做关键字切分。

本清单必须与 `builtins.StdLib` 实际注册的名字保持一致；
`tests.py` 中有一致性断言，防止两处清单漂移。
"""

